#!/usr/bin/env node
// TASK-015: the env fixtures of the TRD-251 separation guard.
//
//   node ops/vendor-mail/lib/fixture-env.mjs          # print the drift, exit 1 on any
//   node ops/vendor-mail/lib/fixture-env.mjs --write  # regenerate __fixtures__/env/
//
// The five env files under ops/vendor-mail/__fixtures__/env/ are GENERATED from
// the real templates (infra/host/templates/env), the way gremion-init-secrets
// renders them, with two differences that make them a guard input:
//   * every generated sentinel GROUP gets its own, distinct, obviously fake
//     value (fixture-<group>-value), so a compose value that resolves to a
//     vendor group's value names that group and no other;
//   * every operator sentinel gets a documentation value (RFC 5737 / 3849
//     addresses, RFC 2606 names), never a real host.
// They are never test/host/fixtures/pooled-stack/**, whose secrets are all one
// placeholder and which carry no vendor key at all: a separation check over
// one shared placeholder value is vacuous by construction.
// vendor-mail.test.mjs fails when a committed fixture drifts from what this
// generator produces for the current templates.
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { envMap, readTemplates, REPO_ROOT, sha256 } from './env.mjs'

export const FIXTURE_ENV_DIR = path.join(REPO_ROOT, 'ops', 'vendor-mail', '__fixtures__', 'env')
export const FIXTURE_REL = 'ops/vendor-mail/__fixtures__/env'
export const FIXTURE_STACK = 't015fx'
export const FIXTURE_DOMAIN = 'example.org'

export const groupValue = (group) => `fixture-${group.replace(/_/g, '-')}-value`

function operatorValue(name) {
  const n = (parseInt(sha256(name).slice(0, 4), 16) % 200) + 20
  if (name === 'platform_domain') return FIXTURE_DOMAIN
  if (name === 'production_stack') return 'none'
  if (name === 'alert_email_from' || name === 'alert_smtp_user') return `alerts@${FIXTURE_DOMAIN}`
  if (name === 'alert_smtp_host') return `mail.${FIXTURE_DOMAIN}`
  if (name.endsWith('_ip6')) return `2001:db8::${n.toString(16)}`
  if (name.endsWith('_ip')) return `192.0.2.${n}`
  if (/(^|_)(uid|gid)$/.test(name)) return '10001'
  if (name.endsWith('_url')) return `https://hooks.${FIXTURE_DOMAIN}/${name}`
  if (/email|_to$|_from$/.test(name)) return `${name.replace(/_/g, '-')}@${FIXTURE_DOMAIN}`
  if (/domain|host/.test(name)) return `${name.replace(/_/g, '-')}.${FIXTURE_DOMAIN}`
  return `fixture-${name.replace(/_/g, '-')}`
}

const HEADER = (name, tmpl) =>
  `# ${FIXTURE_REL}/${name}\n` +
  `# GENERATED by ops/vendor-mail/lib/fixture-env.mjs from infra/host/templates/env/${tmpl}\n` +
  `# (TASK-015). One distinct fake value per generator group; documentation\n` +
  `# addresses and names only. Regenerate with --write; never edit by hand.\n`

function renderOne(text, { colour, state } = {}) {
  const lines = text.split(/\r?\n/).filter((l) => l.length > 0 && !/^\s*#/.test(l))
  let body = lines.join('\n') + '\n'
  body = body.replaceAll('${STACK}', FIXTURE_STACK)
  if (colour) {
    const up = colour.toUpperCase()
    body = body.replaceAll('${COLOUR}', colour)
    body = body.replaceAll('${APP_V4_SUBNET}', state[`APP_${up}_V4_SUBNET`])
    body = body.replaceAll('${APP_V6_SUBNET}', state[`APP_${up}_V6_SUBNET`])
  }
  body = body.replace(/CHANGE_ME_GEN_(hex32|alnum32)_([a-z0-9_]+)/g, (_, _k, g) => groupValue(g))
  body = body.replace(/CHANGE_ME_OPERATOR_([a-z0-9_]+)/g, (_, n) => operatorValue(n))
  // The pins layer is written by the release workflow and never committed; the
  // fixture names its own empty stand-in, as the pooled-stack fixture does --
  // for the state project's layer too (docker-compose.state-pins.yml since
  // TASK-048b; the stand-in is the same empty file).
  body = body.replace(/^COMPOSE_FILE=(.*)$/m, (_, v) =>
    `COMPOSE_FILE=${v.replace(/(^|:)docker-compose\.(?:state-)?pins\.yml/, `$1${FIXTURE_REL}/docker-compose.pins.yml`)}`,
  )
  // Compose splits COMPOSE_FILE on the OS path separator (';' on Windows)
  // unless the env file names one: a ':'-joined list read on Windows is ONE
  // file name, the render fails and arm (b) is unparseable. The pooled-stack
  // fixtures declare it for the same reason.
  if (/^COMPOSE_FILE=.*:/m.test(body) && !/^COMPOSE_PATH_SEPARATOR=/m.test(body)) {
    body = body.replace(/^(COMPOSE_FILE=.*)$/m, (line) => `${line}\nCOMPOSE_PATH_SEPARATOR=:`)
  }
  return body
}

/** {fileName: text} for the five project env files. */
export function generateFixtureEnvs(templates = readTemplates()) {
  const state = renderOne(templates['state.env.tmpl'])
  const stateMap = envMap(state, 'state.env')
  const files = {
    'state.env': HEADER('state.env', 'state.env.tmpl') + state,
    'app-blue.env': HEADER('app-blue.env', 'app.env.tmpl') + renderOne(templates['app.env.tmpl'], { colour: 'blue', state: stateMap }),
    'app-green.env': HEADER('app-green.env', 'app.env.tmpl') + renderOne(templates['app.env.tmpl'], { colour: 'green', state: stateMap }),
    'mail.env': HEADER('mail.env', 'mail.env.tmpl') + renderOne(templates['mail.env.tmpl']),
    'ops.env': HEADER('ops.env', 'ops.env.tmpl') + renderOne(templates['ops.env.tmpl']),
  }
  for (const [name, text] of Object.entries(files)) {
    if (/CHANGE_ME_|\$\{/.test(text.replace(/^#.*$/gm, ''))) throw new Error(`${name}: a sentinel or placeholder survived the fixture render`)
  }
  return files
}

/** Names of committed fixture files that differ from a fresh generation. */
export function fixtureDrift(dir = FIXTURE_ENV_DIR, templates = readTemplates()) {
  const want = generateFixtureEnvs(templates)
  const drift = []
  for (const [name, text] of Object.entries(want)) {
    let have = null
    try {
      have = readFileSync(path.join(dir, name), 'utf8')
    } catch {
      /* absent is drift */
    }
    if (have !== text) drift.push(name)
  }
  return drift
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--write')) {
    for (const [name, text] of Object.entries(generateFixtureEnvs())) writeFileSync(path.join(FIXTURE_ENV_DIR, name), text)
    console.log(`[fixture-env] wrote ${FIXTURE_REL}/{state,app-blue,app-green,mail,ops}.env`)
  } else {
    const d = fixtureDrift()
    if (d.length) {
      console.error(`[fixture-env] drift from the templates: ${d.join(', ')} -- regenerate with --write`)
      process.exit(1)
    }
    console.log('[fixture-env] OK: fixtures match the templates')
  }
}
