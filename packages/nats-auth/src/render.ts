// packages/nats-auth/src/render.ts (@gremion/nats-auth)
//
// renderServerConfig(): the accounts file docker/nats/nats.conf includes, from
// PUBLIC keys only. Deterministic: tenants sorted, the admin first, modules
// sorted, so the same state always renders the same bytes -- which is how
// ensureTenantAccount() knows a second identical call has nothing to reload.
//
// One account per tenant (T_<tenant>, JetStream enabled) holding that tenant's
// admin and one user per flow module; the SYS account holds only the reload
// user. No no_auth_user and no global authorization block exist anywhere: a
// connection without a known nkey is refused (Q1: static config, no JWT
// resolver).
import { fromPublic } from '@nats-io/nkeys'
import {
  accountFor,
  adminPermissions,
  assertModuleId,
  assertTenantId,
  modulePermissions,
  type Permissions,
  SYS_RELOAD_PERMISSIONS,
} from './permissions.ts'

export interface TenantState {
  tenant: string
  /** The tenant admin's user public key. */
  admin: string
  /** catalogue id (or kernel) -> user public key. */
  modules: Record<string, string>
}

export interface ServerState {
  /** The SYS reload user's public key. */
  sysReload: string
  tenants: TenantState[]
}

/** Per-tenant JetStream ceilings [A] (TRD-177 sizing): one tenant -- or a
 *  module flooding its stream -- cannot exhaust the server-wide store
 *  (nats.conf max_file_store) for every other tenant. Four streams exist per
 *  tenant today (the admin creates them); consumers are the modules'
 *  ephemeral ordered consumers plus the admin's. */
export const TENANT_JETSTREAM_LIMITS = '{ max_mem: 8M, max_file: 512M, max_streams: 8, max_consumers: 64 }'

export const HEADER = [
  '# GENERATED by @gremion/nats-auth (ensureTenantAccount / nats-auth init). Do not edit:',
  '# the seeds in the nats-secrets volume are the source of truth and every run re-renders',
  '# this file from them. PUBLIC keys only. Included by docker/nats/nats.conf.',
]

function assertUserPublicKey(k: string, what: string): void {
  let ok = false
  try {
    ok = k.startsWith('U') && fromPublic(k).getPublicKey() === k
  } catch {
    ok = false
  }
  if (!ok) throw new Error(`[nats-auth] ${what} is not a user public key`)
}

const list = (xs: readonly string[]): string => `[${xs.map((x) => JSON.stringify(x)).join(', ')}]`

function renderPermissions(p: Readonly<Permissions>): string {
  const side = (s: { allow: string[]; deny: string[] }): string =>
    s.deny.length ? `{ allow: ${list(s.allow)}, deny: ${list(s.deny)} }` : `{ allow: ${list(s.allow)} }`
  return `{ publish: ${side(p.publish)}, subscribe: ${side(p.subscribe)} }`
}

const user = (comment: string, nkey: string, p: Readonly<Permissions>): string[] => [
  `      # ${comment}`,
  `      { nkey: ${JSON.stringify(nkey)}, permissions: ${renderPermissions(p)} }`,
]

export function renderServerConfig(state: ServerState): string {
  const seen = new Set<string>()
  const use = (k: string, what: string): string => {
    assertUserPublicKey(k, what)
    if (seen.has(k)) throw new Error(`[nats-auth] public key of ${what} is used twice`)
    seen.add(k)
    return k
  }
  const lines: string[] = [...HEADER, 'accounts {', '  SYS {', '    users: [']
  lines.push(...user('reload (SYS)', use(state.sysReload, 'the SYS reload user'), SYS_RELOAD_PERMISSIONS))
  lines.push('    ]', '  }')

  const tenants = [...state.tenants].sort((a, b) => (a.tenant < b.tenant ? -1 : a.tenant > b.tenant ? 1 : 0))
  for (let i = 1; i < tenants.length; i++) {
    if (tenants[i]!.tenant === tenants[i - 1]!.tenant) throw new Error(`[nats-auth] tenant ${tenants[i]!.tenant} listed twice`)
  }
  for (const t of tenants) {
    assertTenantId(t.tenant)
    lines.push(`  ${accountFor(t.tenant)} {`, `    jetstream: ${TENANT_JETSTREAM_LIMITS}`, '    users: [')
    lines.push(...user(`admin@${t.tenant}`, use(t.admin, `admin@${t.tenant}`), adminPermissions(t.tenant)))
    for (const m of Object.keys(t.modules).sort()) {
      assertModuleId(m)
      lines.push(...user(`${m}@${t.tenant}`, use(t.modules[m]!, `${m}@${t.tenant}`), modulePermissions(t.tenant, m)))
    }
    lines.push('    ]', '  }')
  }
  lines.push('}', '')
  return lines.join('\n')
}
