function openApiTypescriptBin(): string {
  return join(PACKAGE_ROOT, 'node_modules', 'openapi-typescript', 'bin', 'cli.js')
}

/** Run openapi-typescript over a spec and return its raw stdout (the `paths`/
 *  `components` interface text). Throws if the tool errors — codegen has no
 *  "best effort" mode; a tool that fails must fail the caller, not emit a
 *  half-generated file. */
function runOpenApiTypescript(repoRoot: string, specFile: string): string {
  const bin = openApiTypescriptBin()
  const specPath = join(repoRoot, specFile)
  return execFileSync(process.execPath, [bin, specPath], { encoding: 'utf8', cwd: repoRoot })
}

/** The exact text `tools/generate.mjs` writes to `spec.outputFile`, and the
 *  exact text `codegen-drift.ts` compares the file on disk against. Pure
 *  function of the spec file's current content — no other state. */
export function generateClientSource(repoRoot: string, spec: GeneratedClientSpec): string {
  const rawTypes = runOpenApiTypescript(repoRoot, spec.specFile).replace(/\r\n/g, '\n').trimEnd()
  return [
    `// AUTO-GENERATED by \`pnpm --filter @gremion/generated-clients generate\` from ${spec.specFile}.`,
    '// DO NOT EDIT BY HAND. A hand edit, or a spec change with no regeneration, both fail',
    '// `pnpm --filter @gremion/generated-clients contracts:check` (src/codegen-drift.ts).',
    '/* eslint-disable */',
    '',
    "import createClient from 'openapi-fetch'",
    '',
    rawTypes,
    '',
    `export function ${spec.factoryName}(options: Parameters<typeof createClient>[0]) {`,
    '  return createClient<paths>(options)',
    '}',
    '',
  ].join('\n')
}
