// packages/generated-clients/src/codegen.ts
//
// Shared codegen logic for `tools/generate.mjs` (writes the generated client)
// and `codegen-drift.ts` (recomputes the SAME content to catch a hand edit, a
// spec changed without regeneration, or a missing output — brief T6). Node 26
// runs a `.ts` file directly (native type-stripping, verified empirically:
// `node foo.ts` on this toolchain), so both the plain-node tool script and
// the compiled package import this one function — two independent
// implementations computing two different answers would BE the drift this
// file exists to catch, so there is deliberately only one.
import { execFileSync } from 'node:child_process'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

// Resolved from THIS FILE's own location, never from the `repoRoot` a caller
// passes in: the openapi-typescript devDependency always lives next to this
// package's own node_modules, regardless of which tree's spec is being read
// (a test fixture repo root has no node_modules of its own — see
// codegen-drift.test.ts, which points `repoRoot` at a scratch dir but still
// needs the REAL tool).
const PACKAGE_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

export interface GeneratedClientSpec {
  /** repo-root-relative path to the OpenAPI spec this client is generated from */
  specFile: string
  /** repo-root-relative path to the generated output file */
  outputFile: string
  /** exported factory function name, e.g. createKernelGovernanceClient */
  factoryName: string
}

