#!/usr/bin/env node
// packages/tenant-store/test/harness/stack.mjs
//
// The integration suite's scratch stack (section 9 of the brief), and the only
// thing `pnpm --filter @gremion/tenant-store test:integration` runs:
//
//   1. writes a checkout-unique, gitignored docker-compose.local-testdb.yml,
//      project t020-<sha8> (sha8 = sha256 of this checkout's real path), with
//      ONE Postgres 18 service on the image of docker-compose.yml's
//      x-module-postgres anchor (the TASK-019 digest pin) holding every
//      database (labelled org.gremion.postgres=kernel), a SECOND one on the
//      same image labelled module:lcfix (TASK-021 G2: the lifecycle's module
//      server `pgm`), plus a PgBouncer in transaction mode in front of the first (the Q3
//      spec: the runner must refuse it, a runtime pool may use it); volume
//      and network renamed t020-<sha8>-*, published on 127.0.0.1 only, on
//      free ports;
//   2. asserts all of that on `docker compose config` BEFORE `up`;
//   3. runs vitest with vitest.integration.config.ts;
//   4. tears down BY EXPLICIT NAME in a trap (exit, SIGINT, SIGTERM): the
//      container, the volume and the network this run created. It never runs
//      `docker compose down` and never prunes. T020_KEEP_STACK=1 keeps them.
import { spawnSync } from 'node:child_process'
import { createHash, randomBytes } from 'node:crypto'
import { readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs'
import { createServer } from 'node:net'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const PKG = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const REPO = resolve(PKG, '../..')
const COMPOSE_FILE = join(PKG, 'docker-compose.local-testdb.yml')
const STATE_FILE = join(PKG, '.testdb-state.json')

export const sha8 = createHash('sha256').update(realpathSync(REPO)).digest('hex').slice(0, 8)
export const project = `t020-${sha8}`
export const names = {
  container: `${project}-pg`,
  pooler: `${project}-pooler`,
  volume: `${project}-pgdata`,
  network: `${project}-net`,
  // TASK-021 (G2): a second PG18 server labelled module:<id>, the lifecycle's
  // module server (one server per module, D14), beside the kernel one.
  moduleContainer: `${project}-pgm`,
  moduleVolume: `${project}-pgmdata`,
}

/** The fixture module whose server `pgm` is (TASK-021 lifecycle specs). */
export const MODULE_FIXTURE_ID = 'lcfix'

/** Test-only: PgBouncer 1.25.2, transaction pooling, pinned by digest. */
export const POOLER_IMAGE = 'edoburu/pgbouncer@sha256:4c1ca296ef525f108f5d3552cc337c0c09587cf8dae7f0067fd93349e47dc1cd'

/** The image of the x-module-postgres anchor in the kernel compose file (TASK-019). */
export function moduleImage(composeText = readFileSync(join(REPO, 'docker-compose.yml'), 'utf8')) {
  const lines = composeText.split('\n')
  const start = lines.findIndex((l) => l.startsWith('x-module-postgres:'))
  if (start < 0) throw new Error('docker-compose.yml has no x-module-postgres anchor')
  for (const l of lines.slice(start + 1)) {
    if (/^\S/.test(l)) break
    const m = /^\s+image:\s*(\S+)\s*$/.exec(l)
    if (m) {
      if (!/^postgres:18[^@]*@sha256:[0-9a-f]{64}$/.test(m[1])) throw new Error(`x-module-postgres image is not a digest-pinned postgres:18: ${m[1]}`)
      return m[1]
    }
  }
  throw new Error('x-module-postgres has no image:')
}

function freePort() {
  return new Promise((res, rej) => {
    const s = createServer()
    s.once('error', rej)
    s.listen(0, '127.0.0.1', () => {
      const { port } = s.address()
      s.close(() => res(port))
    })
  })
}

function sh(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { encoding: 'utf8', ...opts })
  if (r.status !== 0 && !opts.allowFail) {
    throw new Error(`${cmd} ${args.join(' ')} exited ${r.status}: ${(r.stderr || '').trim()}`)
  }
  return r
}

const compose = (...args) => ['compose', '-p', project, '-f', COMPOSE_FILE, ...args]

export function composeYaml({ image, port, poolerPort, modulePort, user, password, db }) {
  return `# GENERATED by packages/tenant-store/test/harness/stack.mjs — gitignored, checkout-unique.
name: ${project}
services:
  pg:
    image: ${image}
    container_name: ${names.container}
    labels:
      org.gremion.postgres: "kernel"
    environment:
      POSTGRES_USER: ${user}
      POSTGRES_PASSWORD: ${password}
      POSTGRES_DB: ${db}
    ports:
      - "127.0.0.1:${port}:5432"
    volumes:
      - pgdata:/var/lib/postgresql
    networks:
      - net
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -h 127.0.0.1 -U ${user} -d ${db}"]
      interval: 1s
      timeout: 3s
      retries: 60
  pgm:
    image: ${image}
    container_name: ${names.moduleContainer}
    labels:
      org.gremion.postgres: "module:${MODULE_FIXTURE_ID}"
    environment:
      POSTGRES_USER: ${user}
      POSTGRES_PASSWORD: ${password}
    ports:
      - "127.0.0.1:${modulePort}:5432"
    volumes:
      - pgmdata:/var/lib/postgresql
    networks:
      - net
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -h 127.0.0.1 -U ${user} -d postgres"]
      interval: 1s
      timeout: 3s
      retries: 60
  pooler:
    image: ${POOLER_IMAGE}
    container_name: ${names.pooler}
    environment:
      DB_HOST: pg
      DB_USER: ${user}
      DB_PASSWORD: ${password}
      POOL_MODE: transaction
      AUTH_TYPE: scram-sha-256
    ports:
      - "127.0.0.1:${poolerPort}:5432"
    networks:
      - net
    depends_on:
      pg:
        condition: service_healthy
volumes:
  pgdata:
    name: ${names.volume}
  pgmdata:
    name: ${names.moduleVolume}
networks:
  net:
    name: ${names.network}
`
}

/** Asserts the rendered config before anything is created. Returns the problems. */
export function checkRenderedConfig(cfg, { image, port, poolerPort, modulePort }) {
  const problems = []
  if (cfg.name !== project) problems.push(`project name ${cfg.name}, expected ${project}`)
  const expected = {
    pg: { image, container: names.container, port },
    pgm: { image, container: names.moduleContainer, port: modulePort },
    pooler: { image: POOLER_IMAGE, container: names.pooler, port: poolerPort },
  }
  const services = Object.entries(cfg.services ?? {})
  const got = services.map(([n]) => n).sort().join(',')
  if (got !== 'pg,pgm,pooler') problems.push(`services [${got}], expected exactly [pg,pgm,pooler]`)
  for (const [name, svc] of services) {
    const want = expected[name]
    if (!want) continue
    if (svc.image !== want.image) problems.push(`service ${name} image ${svc.image}, expected ${want.image}`)
    if (svc.container_name !== want.container) problems.push(`service ${name} container_name ${svc.container_name}`)
    if ((svc.ports ?? []).length !== 1) problems.push(`service ${name} publishes ${(svc.ports ?? []).length} ports, expected 1`)
    for (const p of svc.ports ?? []) {
      if (p.host_ip !== '127.0.0.1') problems.push(`service ${name} publishes on ${p.host_ip || 'all interfaces'}`)
      if (String(p.published) !== String(want.port)) problems.push(`service ${name} publishes port ${p.published}, expected ${want.port}`)
    }
    for (const v of svc.volumes ?? []) {
      if (v.type !== 'volume') problems.push(`service ${name} mounts a ${v.type} (${v.source}), only named volumes are allowed`)
    }
  }
  for (const [key, v] of Object.entries(cfg.volumes ?? {})) {
    if (!String(v.name).startsWith(`${project}-`)) problems.push(`volume ${key} is named ${v.name}, not ${project}-*`)
  }
  for (const [key, n] of Object.entries(cfg.networks ?? {})) {
    if (!String(n.name).startsWith(`${project}-`)) problems.push(`network ${key} is named ${n.name}, not ${project}-*`)
  }
  if (Object.keys(cfg.volumes ?? {}).length === 0) problems.push('no named volume')
  if (Object.keys(cfg.networks ?? {}).length === 0) problems.push('no named network')
  return problems
}

let created = false
function teardown() {
  if (!created) return
  created = false
  if (process.env.T020_KEEP_STACK === '1') {
    console.error(`[t020] T020_KEEP_STACK=1: keeping ${names.container}, ${names.moduleContainer}, ${names.volume}, ${names.moduleVolume}, ${names.network}`)
    return
  }
  // By explicit name only. Never `compose down`, never prune. A resource
  // that is already gone is fine; anything else left behind fails the run.
  const left = []
  for (const [what, args] of /** @type {[string, string[]][]} */ ([
    ['container', ['rm', '-f', '-v', names.pooler]],
    ['container', ['rm', '-f', '-v', names.container]],
    ['container', ['rm', '-f', '-v', names.moduleContainer]],
    ['volume', ['volume', 'rm', names.volume]],
    ['volume', ['volume', 'rm', names.moduleVolume]],
    ['network', ['network', 'rm', names.network]],
  ])) {
    const r = sh('docker', args, { allowFail: true })
    if (r.status !== 0 && !/no such/i.test(r.stderr ?? '')) left.push(`${what} ${args.at(-1)}: ${(r.stderr ?? '').trim()}`)
  }
  rmSync(STATE_FILE, { force: true })
  if (left.length) {
    console.error(`[t020] teardown left resources behind:\n  ${left.join('\n  ')}`)
    process.exitCode = 1
  }
}

async function main() {
  const image = moduleImage()
  const port = await freePort()
  let poolerPort = await freePort()
  while (poolerPort === port) poolerPort = await freePort()
  let modulePort = await freePort()
  while (modulePort === port || modulePort === poolerPort) modulePort = await freePort()
  const user = 't020_test'
  const db = 't020_test_admin'
  const password = randomBytes(18).toString('base64url')
  writeFileSync(COMPOSE_FILE, composeYaml({ image, port, poolerPort, modulePort, user, password, db }))

  const cfg = JSON.parse(sh('docker', compose('config', '--format', 'json')).stdout)
  const problems = checkRenderedConfig(cfg, { image, port, poolerPort, modulePort })
  if (problems.length) throw new Error(`refusing to start the scratch stack:\n  ${problems.join('\n  ')}`)

  process.on('exit', teardown)
  process.on('SIGINT', () => process.exit(130))
  process.on('SIGTERM', () => process.exit(143))
  created = true
  sh('docker', compose('up', '-d', '--wait', '--wait-timeout', '120'), { stdio: ['ignore', 'inherit', 'inherit'] })

  writeFileSync(
    STATE_FILE,
    JSON.stringify({ sha8, port, poolerPort, modulePort, user, password, db, image, moduleContainer: names.moduleContainer, moduleId: MODULE_FIXTURE_ID, composeFile: COMPOSE_FILE }),
  )
  const r = spawnSync('pnpm', ['exec', 'vitest', 'run', '--config', 'vitest.integration.config.ts', ...process.argv.slice(2)], {
    cwd: PKG,
    stdio: 'inherit',
    env: { ...process.env, T020_STATE: STATE_FILE, T020_SCRATCH: sha8 },
  })
  process.exitCode = r.status === 0 ? 0 : r.status ?? 1
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(`[t020] ${err.message}`)
    process.exitCode = 1
  })
}
