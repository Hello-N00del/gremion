#!/usr/bin/env node
// packages/tenant-store/test/harness/stack.mjs
//
// The integration suite's scratch stack (section 9 of the brief), and the only
// thing `pnpm --filter @gremion/tenant-store test:integration` runs:
//
//   1. writes a checkout-unique, gitignored docker-compose.local-testdb.yml,
//      project t020-<sha8> (sha8 = sha256 of this checkout's real path), with
//      ONE Postgres 18 service on the image of docker-compose.yml's
//      x-module-postgres anchor (the TASK-019 digest pin), its volume and
//      network renamed t020-<sha8>-*, published on 127.0.0.1 only, on a
//      free port;
//   2. asserts all of that on `docker compose config` BEFORE `up`;
//   3. runs vitest with vitest.integration.config.ts;
//   4. tears down BY EXPLICIT NAME in a trap (exit, SIGINT, SIGTERM): the
//      container, the volume and the network this run created. It never runs
//      `docker compose down` and never prunes. T020_KEEP_STACK=1 keeps them.
import { spawnSync } from 'node:child_process'
import { createHash, randomBytes } from 'node:crypto'
import { readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs'
import { createServer } from 'node:net'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const PKG = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const REPO = resolve(PKG, '../..')
const COMPOSE_FILE = join(PKG, 'docker-compose.local-testdb.yml')
const STATE_FILE = join(PKG, '.testdb-state.json')

export const sha8 = createHash('sha256').update(realpathSync(REPO)).digest('hex').slice(0, 8)
export const project = `t020-${sha8}`
export const names = {
  container: `${project}-pg`,
  volume: `${project}-pgdata`,
  network: `${project}-net`,
}

/** The image of the x-module-postgres anchor in the kernel compose file (TASK-019). */
export function moduleImage(composeText = readFileSync(join(REPO, 'docker-compose.yml'), 'utf8')) {
  const lines = composeText.split('\n')
  const start = lines.findIndex((l) => /^x-module-postgres:/.test(l))
  if (start < 0) throw new Error('docker-compose.yml has no x-module-postgres anchor')
  for (const l of lines.slice(start + 1)) {
    if (/^\S/.test(l)) break
    const m = /^\s+image:\s*(\S+)\s*$/.exec(l)
    if (m) {
      if (!/^postgres:18[^@]*@sha256:[0-9a-f]{64}$/.test(m[1])) throw new Error(`x-module-postgres image is not a digest-pinned postgres:18: ${m[1]}`)
      return m[1]
    }
  }
  throw new Error('x-module-postgres has no image:')
}

function freePort() {
  return new Promise((res, rej) => {
    const s = createServer()
    s.once('error', rej)
    s.listen(0, '127.0.0.1', () => {
      const { port } = s.address()
      s.close(() => res(port))
    })
  })
}

function sh(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { encoding: 'utf8', ...opts })
  if (r.status !== 0 && !opts.allowFail) {
    throw new Error(`${cmd} ${args.join(' ')} exited ${r.status}: ${(r.stderr || '').trim()}`)
  }
  return r
}

const compose = (...args) => ['compose', '-p', project, '-f', COMPOSE_FILE, ...args]

export function composeYaml({ image, port, user, password, db }) {
  return `# GENERATED by packages/tenant-store/test/harness/stack.mjs — gitignored, checkout-unique.
name: ${project}
services:
  pg:
    image: ${image}
    container_name: ${names.container}
    environment:
      POSTGRES_USER: ${user}
      POSTGRES_PASSWORD: ${password}
      POSTGRES_DB: ${db}
    ports:
      - "127.0.0.1:${port}:5432"
    volumes:
      - pgdata:/var/lib/postgresql
    networks:
      - net
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -h 127.0.0.1 -U ${user} -d ${db}"]
      interval: 1s
      timeout: 3s
      retries: 60
volumes:
  pgdata:
    name: ${names.volume}
networks:
  net:
    name: ${names.network}
`
}

/** Asserts the rendered config before anything is created. Returns the problems. */
export function checkRenderedConfig(cfg, { image, port }) {
  const problems = []
  if (cfg.name !== project) problems.push(`project name ${cfg.name}, expected ${project}`)
  const services = Object.entries(cfg.services ?? {})
  if (services.length !== 1) problems.push(`${services.length} services, expected exactly 1`)
  for (const [name, svc] of services) {
    if (svc.image !== image) problems.push(`service ${name} image ${svc.image}, expected ${image}`)
    if (svc.container_name !== names.container) problems.push(`service ${name} container_name ${svc.container_name}`)
    for (const p of svc.ports ?? []) {
      if (p.host_ip !== '127.0.0.1') problems.push(`service ${name} publishes on ${p.host_ip || 'all interfaces'}`)
      if (String(p.published) !== String(port)) problems.push(`service ${name} publishes port ${p.published}, expected ${port}`)
    }
    for (const v of svc.volumes ?? []) {
      if (v.type !== 'volume') problems.push(`service ${name} mounts a ${v.type} (${v.source}), only named volumes are allowed`)
    }
  }
  for (const [key, v] of Object.entries(cfg.volumes ?? {})) {
    if (!String(v.name).startsWith(`${project}-`)) problems.push(`volume ${key} is named ${v.name}, not ${project}-*`)
  }
  for (const [key, n] of Object.entries(cfg.networks ?? {})) {
    if (!String(n.name).startsWith(`${project}-`)) problems.push(`network ${key} is named ${n.name}, not ${project}-*`)
  }
  if (Object.keys(cfg.volumes ?? {}).length === 0) problems.push('no named volume')
  if (Object.keys(cfg.networks ?? {}).length === 0) problems.push('no named network')
  return problems
}

let created = false
function teardown() {
  if (!created) return
  created = false
  if (process.env.T020_KEEP_STACK === '1') {
    console.error(`[t020] T020_KEEP_STACK=1: keeping ${names.container}, ${names.volume}, ${names.network}`)
    return
  }
  // By explicit name only. Never `compose down`, never prune.
  sh('docker', ['rm', '-f', '-v', names.container], { allowFail: true })
  sh('docker', ['volume', 'rm', names.volume], { allowFail: true })
  sh('docker', ['network', 'rm', names.network], { allowFail: true })
  rmSync(STATE_FILE, { force: true })
}

async function main() {
  const image = moduleImage()
  const port = await freePort()
  const user = 't020_test'
  const db = 't020_test_admin'
  const password = randomBytes(18).toString('base64url')
  writeFileSync(COMPOSE_FILE, composeYaml({ image, port, user, password, db }))

  const cfg = JSON.parse(sh('docker', compose('config', '--format', 'json')).stdout)
  const problems = checkRenderedConfig(cfg, { image, port })
  if (problems.length) throw new Error(`refusing to start the scratch stack:\n  ${problems.join('\n  ')}`)

  process.on('exit', teardown)
  for (const sig of ['SIGINT', 'SIGTERM']) process.on(sig, () => process.exit(130))
  created = true
  sh('docker', compose('up', '-d', '--wait', '--wait-timeout', '120'), { stdio: ['ignore', 'inherit', 'inherit'] })

  writeFileSync(STATE_FILE, JSON.stringify({ sha8, port, user, password, db, image }))
  const r = spawnSync('pnpm', ['exec', 'vitest', 'run', '--config', 'vitest.integration.config.ts', ...process.argv.slice(2)], {
    cwd: PKG,
    stdio: 'inherit',
    env: { ...process.env, T020_STATE: STATE_FILE, T020_SCRATCH: sha8 },
  })
  process.exitCode = r.status ?? 1
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(`[t020] ${err.message}`)
    process.exitCode = 1
  })
}
