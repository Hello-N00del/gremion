#!/usr/bin/env node
// node --test scripts/check-council-requester-wired.test.mjs
//
// Deploy wiring for council module self-service. The role (gremion_ui_modules)
// is made by `gremion-tenant init` (ensureCouncilRequester, gated on
// UI_MODULES_DB_PASSWORD) and gremion-ui connects as it through
// PLATFORM_MODULES_DATABASE_URL. This guard pins every hop: the password is
// generated once by the secrets bootstrap (one sentinel group, state.env + both
// colours), the init one-shot receives it, gremion-ui's URL is built from it
// (no inline secret) and only when the password is set, and the dev generator
// and docs know it. The password is OPTIONAL on purpose: unset or empty gives
// an empty URL and the settings section reports "not configured" (the safety
// switch for self-service switching), so no compose variable may be required.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), 'utf8')

function serviceBlock(text, name) {
  const start = text.search(new RegExp(`^  ${name}:`, 'm'))
  assert.ok(start >= 0, `service ${name} not found`)
  const rest = text.slice(start + 1)
  const next = rest.search(/^  [a-z][\w-]*:/m)
  return next < 0 ? rest : rest.slice(0, next)
}

const SENTINEL = 'CHANGE_ME_GEN_alnum32_ui_modules_db'

test('both env templates share one generated sentinel group for UI_MODULES_DB_PASSWORD', () => {
  for (const f of ['app.env.tmpl', 'state.env.tmpl']) {
    assert.match(read(`infra/host/templates/env/${f}`), new RegExp(`^UI_MODULES_DB_PASSWORD=${SENTINEL}$`, 'm'), f)
  }
})

test('compose tenant-create passes an OPTIONAL UI_MODULES_DB_PASSWORD (:-) to init', () => {
  const b = serviceBlock(read('docker-compose.app.yml'), 'tenant-create')
  assert.match(b, /^\s+UI_MODULES_DB_PASSWORD: \$\{UI_MODULES_DB_PASSWORD:-\}\s*$/m)
  assert.doesNotMatch(b, /UI_MODULES_DB_PASSWORD:\?/, 'the password must stay optional')
})

test('compose gremion-ui builds PLATFORM_MODULES_DATABASE_URL from the secret only when it is set, direct to gremion_platform, no inline secret', () => {
  const b = serviceBlock(read('docker-compose.app.yml'), 'gremion-ui')
  const m = b.match(/^\s+PLATFORM_MODULES_DATABASE_URL: (.+)$/m)
  assert.ok(m, 'PLATFORM_MODULES_DATABASE_URL missing')
  assert.match(
    m[1],
    /^\$\{UI_MODULES_DB_PASSWORD:\+postgresql:\/\/gremion_ui_modules:\$\{UI_MODULES_DB_PASSWORD\}@postgres-\$\{STACK:\?[^}]+\}:5432\/gremion_platform\}$/,
  )
  assert.doesNotMatch(b, /UI_MODULES_DB_PASSWORD:\?/, 'the password must stay optional')
})

test('the generator sentinel group is also generated by the secrets bootstrap', () => {
  const init = read('infra/host/bin/gremion-init-secrets')
  assert.ok(init.includes('CHANGE_ME_GEN_alnum32_<group>'), 'bootstrap no longer documents the alnum32 sentinel')
  // One value per group across files: state.env and app.env carry the same group name.
  const groups = (f) => [...read(`infra/host/templates/env/${f}`).matchAll(/CHANGE_ME_GEN_alnum32_ui_modules_db/g)].length
  assert.equal(groups('app.env.tmpl'), 1)
  assert.equal(groups('state.env.tmpl'), 1)
})

test('the dev generator mints UI_MODULES_DB_PASSWORD (.env.example placeholder replaced by setup.sh)', () => {
  const m = read('.env.example').match(/^UI_MODULES_DB_PASSWORD=(CHANGE_ME\w+)$/m)
  assert.ok(m, 'UI_MODULES_DB_PASSWORD missing from .env.example')
  assert.ok(read('scripts/setup.sh').includes(m[1]), `${m[1]} not replaced by setup.sh`)
})

test('the pooled-stack proof renders UI_MODULES_DB_PASSWORD into app env', () => {
  assert.match(read('test/host/integration/pooled-stack-proof.sh'), /^UI_MODULES_DB_PASSWORD=/m)
})

test('the layout doc names the role and its variable', () => {
  const d = read('docs/ops/pooled-stack-layout.md')
  assert.ok(d.includes('UI_MODULES_DB_PASSWORD') && d.includes('gremion_ui_modules'))
})

test('every render and env fixture that carries UI_OAC_DB_PASSWORD also carries UI_MODULES_DB_PASSWORD', () => {
  const files = [
    'test/host/fixtures/pooled-stack/app-blue.env',
    'test/host/fixtures/pooled-stack/app-green.env',
    'scripts/release/fixtures/render/render.env',
    'scripts/verify/census/render.env',
    'ops/vendor-mail/__fixtures__/env/app-blue.env',
    'ops/vendor-mail/__fixtures__/env/app-green.env',
    'ops/vendor-mail/__fixtures__/env/state.env',
  ]
  for (const f of files) {
    const t = read(f)
    assert.match(t, /^UI_OAC_DB_PASSWORD=/m, `${f}: expected the OAC twin to still be there`)
    assert.match(t, /^UI_MODULES_DB_PASSWORD=/m, `${f}: UI_MODULES_DB_PASSWORD missing`)
  }
})
