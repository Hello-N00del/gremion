cd_lib() {
    local snippet="$1"
    shift
    bash -c "set -euo pipefail
. \"\${HOST_SRC}/lib/common.sh\"
. \"\${HOST_SRC}/lib/cd/core.sh\"
. \"\${HOST_SRC}/lib/cd/cmd-state.sh\"
. \"\${GREMION_CD_STUBS_DIR}/cd-stubs.sh\"
${snippet}" cd-lib "$@"
}

cd_prog() { "${HOST_SRC}/bin/gremion-cd" "$@"; }

# cd_bg 'snippet' -- the snippet runs in the background (same prelude as cd_lib) with
# bats' fd 3 closed; it must print "ready". CD_BG_PID, CD_BG_OUT. A snippet that wants
# to be killed with -9 ends in `exec sleep 300` so the pid stays the same.
cd_bg() {
    local snippet="$1" i
    CD_BG_OUT="$(mktemp "${GREMION_ROOT}/.bg.XXXXXX")"
    bash -c "set -euo pipefail
. \"\${HOST_SRC}/lib/common.sh\"
. \"\${HOST_SRC}/lib/cd/core.sh\"
. \"\${HOST_SRC}/lib/cd/cmd-state.sh\"
. \"\${GREMION_CD_STUBS_DIR}/cd-stubs.sh\"
${snippet}" cd-bg > "$CD_BG_OUT" 2>&1 3>&- < /dev/null &
    CD_BG_PID=$!
    CD_BG_PIDS+=("$CD_BG_PID")
    for i in $(seq 1 100); do
        grep -q '^ready' "$CD_BG_OUT" 2>/dev/null && return 0
        sleep 0.1
    done
    echo "cd_bg: never ready; output:" >&2
    cat "$CD_BG_OUT" >&2
    return 1
}

# cd_need_flock -- the lock tests need util-linux flock (the bats image has it).
cd_need_flock() {
    command -v flock >/dev/null 2>&1 || skip "flock (util-linux) is not installed"
}

# cd_git_fixture -- a bare mirror at data/cd/mirror.git:
#   c1 - c2 - c3   (main)
#     \_ d1        (side)
# Sets C1 C2 C3 D1 (full SHAs).
cd_git_fixture() {
    local work="${GREMION_ROOT}/.fixture-work" bare="${GREMION_ROOT}/data/cd/mirror.git"
    local g=gi
    g="${g}t"
    export GIT_AUTHOR_NAME=t GIT_AUTHOR_EMAIL=t@example.org GIT_COMMITTER_NAME=t GIT_COMMITTER_EMAIL=t@example.org
    "$g" init -q -b main "$work"
    "$g" -C "$work" commit -q --allow-empty -m c1
    C1="$("$g" -C "$work" rev-parse HEAD)"
    "$g" -C "$work" commit -q --allow-empty -m c2
    C2="$("$g" -C "$work" rev-parse HEAD)"
    "$g" -C "$work" commit -q --allow-empty -m c3
    C3="$("$g" -C "$work" rev-parse HEAD)"
    "$g" -C "$work" checkout -q -b side "$C1"
    "$g" -C "$work" commit -q --allow-empty -m d1
    D1="$("$g" -C "$work" rev-parse HEAD)"
    "$g" clone -q --bare "$work" "$bare"
    export C1 C2 C3 D1
}
