#!/usr/bin/env bash
# test/host/test_helper/cd.bash -- the continuous-deployment (gremion-cd) test helper.
#
# Load it AFTER test_helper/host:
#     load 'test_helper/host'
#     load 'test_helper/cd'
#
# WHAT IT GIVES A UNIT TEST
#   cd_setup / cd_teardown      a throwaway $GREMION_ROOT with data/cd and runtime/cd,
#                               a valid etc/cd.env, the fake clock and the stub file
#   cd_write_cfg KEY=VAL ...    rewrite etc/cd.env: the valid base plus overrides
#   cd_base_state               print a valid, idle schema-v1 state document
#   cd_seed_state [JQ_FILTER]   write that document (filtered) as data/cd/state.json
#   cd_fake_now N / cd_advance N / cd_clock   the fake clock (a file, so a background
#                               process sees what the test sets)
#   cd_lib 'snippet' [args]     run a snippet in a fresh bash that sources common.sh,
#                               core.sh, cmd-state.sh and then the stubs (use with `run`)
#   cd_prog args...             run the gremion-cd dispatcher
#   cd_bg 'snippet'             run a snippet in the background; waits for "ready"
#   cd_stub_set FN RC [OUT]     decide what a stubbed cross-unit function does
#
# THE STUBS. Every function of the cross-unit interface list that another unit owns has a
# stub here, so a unit can be tested alone. A stub records its call in $SHIM_LOG
# ("stub <function> <args>") and returns what cd_stub_set told it to (exit code 0 and
# no output by default). The stub FILE (written by cd_setup) defines a stub only when
# no real function of that name exists, so when a unit's real library lands in
# infra/host/lib/cd/ it wins and the stub steps aside.
#
# The fake clock and the stub file are honoured by the program only when
# GREMION_CD_TESTING=1, which cd_setup exports.

CD_HOST_LIB="${HOST_SRC}/lib"
CD_FIXTURES="${HOST_TEST_DIR}/fixtures/cd"

