# _cd_stub_call FN ARGS... -- the body of every stub. CD_STUB_RC_<fn> is the return
# code (default 0), CD_STUB_OUT_<fn> is printed first (default nothing).
_cd_stub_call() {
    local fn="$1" rcv outv
    shift
    printf 'stub %s %s\n' "$fn" "$*" >> "${SHIM_LOG:-/dev/null}"
    outv="CD_STUB_OUT_${fn}"
    rcv="CD_STUB_RC_${fn}"
    if [[ -n "${!outv:-}" ]]; then
        printf '%s\n' "${!outv}"
    fi
    return "${!rcv:-0}"
}

# cd_stub_set FN RC [OUT] -- picked up by the NEXT process (export), and by this one.
cd_stub_set() {
    local fn="$1" rc="$2" out="${3:-}"
    export "CD_STUB_RC_${fn}=${rc}" "CD_STUB_OUT_${fn}=${out}"
}

# cd_write_stub_file PATH -- the sourceable stub file.
cd_write_stub_file() {
    local path="$1" fn
    {
        echo '# generated by test/host/test_helper/cd.bash -- stubs for the cross-unit functions'
        declare -f _cd_stub_call
        for fn in "${CD_STUB_FUNCS[@]}"; do
            printf 'if ! declare -F %s >/dev/null 2>&1; then\n' "$fn"
            printf '%s() { _cd_stub_call %s "$@"; }\n' "$fn" "$fn"
            printf 'fi\n'
        done
    } > "$path"
}

cd_setup() {
    setup_host_root
    mkdir -p "${GREMION_ROOT}/data/cd" "${GREMION_ROOT}/runtime/cd"
    chmod 700 "${GREMION_ROOT}/data/cd" "${GREMION_ROOT}/runtime/cd"
    export GREMION_CD_TESTING=1
    export GREMION_CD_NOW_FILE="${GREMION_ROOT}/.fake-now"
    export GREMION_CD_HB_POLL_S=0.1
    export GREMION_CD_STUBS_DIR="${GREMION_ROOT}/.cd-stubs"
    mkdir -p "$GREMION_CD_STUBS_DIR"
    CD_BG_PIDS=()
    cd_fake_now 1700000000
    cd_write_stub_file "${GREMION_CD_STUBS_DIR}/cd-stubs.sh"
    cd_write_cfg
}

cd_teardown() {
    local p
    for p in "${CD_BG_PIDS[@]:-}"; do
        [[ -n "$p" ]] && kill -9 "$p" 2>/dev/null || true
    done
    # a heartbeat subshell may outlive a killed parent for one poll; give it the time
    sleep 0.3
    teardown_host_root
}

cd_fake_now() { printf '%s\n' "$1" > "$GREMION_CD_NOW_FILE"; }
cd_clock() { cat "$GREMION_CD_NOW_FILE"; }
cd_advance() { cd_fake_now "$(( $(cd_clock) + $1 ))"; }

# cd_write_cfg [KEY=VAL ...] -- etc/cd.env = the valid base, a key replaced by an override.
cd_write_cfg() {
    local cfg="${GREMION_ROOT}/etc/cd.env" kv key tmp
    tmp="$(mktemp)"
    cp "${CD_FIXTURES}/core/cd.env.valid" "$tmp"
    for kv in "$@"; do
        key="${kv%%=*}"
        grep -v "^${key}=" "$tmp" > "${tmp}.2" || true
        mv -f "${tmp}.2" "$tmp"
        printf '%s\n' "$kv" >> "$tmp"
    done
    mkdir -p "${GREMION_ROOT}/etc"
    mv -f "$tmp" "$cfg"
}

# cd_base_state -- a valid idle state document, written out literally here so a test
# does not depend on the program's own cd_state_init.
cd_base_state() {
    cat <<'JSON'
{"v":1,"phase":"idle","hold":null,"live":null,"previous":null,"release":null,
 "poll":{"last_at":"","last_ok":true,"tip12":"","verdict":"none","api_calls_hour":0},
 "notified":{}}
JSON
}

# cd_seed_state [JQ_FILTER] -- data/cd/state.json from the base document.
cd_seed_state() {
    local filter="${1:-.}"
    cd_base_state | jq "$filter" > "${GREMION_ROOT}/data/cd/state.json"
    chmod 600 "${GREMION_ROOT}/data/cd/state.json"
}

