#!/usr/bin/env node
/**
 * Gremion Session-A inversion A1: build-time codegen for the server-init barrel.
 *
 * SCANS gremion-ui/src/lib/server for every `register.server.ts` file (a module's
 * server-side self-registration entrypoint) and writes the committed barrel
 * src/lib/server/modules/server-init.generated.ts — a list of SIDE-EFFECT
 * imports (`import './<rel>/register.server'`) in a deterministic (path-sorted)
 * order.
 *
 * Importing the barrel once (from hooks.server.ts) thereby loads every module's
 * register.server.ts, which registers that module's boot hooks, tenant-evict
 * hooks, and provisioning subsystem factories into runtime-registry.ts. The
 * kernel composition roots (hooks.server.ts / tenant/registry.ts / the
 * governance orchestrator) consume ONLY runtime-registry.ts — they no longer
 * statically import any module's server internals. Adding a new module with a
 * register.server.ts and re-running this script wires it in with ZERO edit to
 * the kernel or to this barrel by hand.
 *
 * It deliberately does NOT use import.meta.glob (which only resolves inside the
 * Vite/SvelteKit graph), so the generated barrel is a plain static side-effect
 * import list — the same posture as scripts/build-module-manifest.mjs.
 *
 * Usage:
 *   node scripts/build-module-server-init.mjs            # write server-init.generated.ts
 *   node scripts/build-module-server-init.mjs --stdout   # print to stdout (staleness guard)
 *
 * Exit codes:
 *   0 — barrel written / printed
 *   1 — failed to read the server tree
 */
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const SERVER_DIR = path.resolve(__dirname, '..', 'src', 'lib', 'server')
const MODULES_DIR = path.join(SERVER_DIR, 'modules')
const OUT_PATH = path.join(MODULES_DIR, 'server-init.generated.ts')

const STDOUT = process.argv.includes('--stdout')

/** Recursively list every `register.server.ts` under src/lib/server. */
function findRegisterFiles(dir) {
  let entries
  try {
    entries = readdirSync(dir)
  } catch (err) {
    console.error(`[server-init] failed to read ${dir}: ${err.message}`)
    process.exit(1)
  }
  const found = []
  for (const name of entries.sort()) {
    const full = path.join(dir, name)
    if (statSync(full).isDirectory()) {
      found.push(...findRegisterFiles(full))
    } else if (name === 'register.server.ts') {
      found.push(full)
    }
  }
  return found
}

function build() {
  const files = findRegisterFiles(SERVER_DIR)
  // Import specifiers are RELATIVE to the barrel's dir (src/lib/server/modules),
  // POSIX-normalized and extension-stripped, sorted for deterministic output.
  const specifiers = files
    .map((full) => {
      const rel = path.relative(MODULES_DIR, full).split(path.sep).join('/').replace(/\.ts$/, '')
      return rel.startsWith('.') ? rel : `./${rel}`
    })
    .sort()

  const imports = specifiers.map((s) => `import '${s}'`).join('\n')

  return (
    '// @generated by scripts/build-module-server-init.mjs — DO NOT EDIT BY HAND.\n' +
    '// Re-run `node scripts/build-module-server-init.mjs` after adding/removing/renaming\n' +
    "// a module's register.server.ts. The committed copy is byte-pinned by\n" +
    "// server-init.generated.test.ts's staleness guard.\n" +
    '//\n' +
    '// SCANNED src/lib/server for register.server.ts files. Importing this barrel\n' +
    '// once (from hooks.server.ts) runs every module\'s self-registration into\n' +
    '// runtime-registry.ts (boot hooks + tenant-evict hooks + provisioning\n' +
    '// subsystem factories). No import.meta.glob (a static import list resolves\n' +
    '// under bare tsx/Node, not just the Vite graph).\n' +
    imports +
    '\n'
  )
}

function main() {
  const out = build()
  if (STDOUT) {
    process.stdout.write(out)
    return
  }
  writeFileSync(OUT_PATH, out, 'utf-8')
  console.info(`[server-init] wrote ${OUT_PATH}`)
}

main()
