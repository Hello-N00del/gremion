#!/usr/bin/env node
/**
 * WP2-1: build-time codegen for the module-manifest registry barrel.
 *
 * SCANS gremion-ui/src/lib/modules/manifests/*.ts, extracts each file's exported
 * `<name>Manifest` const and its `order:` rank, and writes the committed barrel
 * src/lib/modules/manifests/index.generated.ts — a synchronous re-export of the
 * MODULE_MANIFESTS array in registration (order-field) order.
 *
 * This REPLACES the hand-maintained array literal in manifests/index.ts that
 * named each module: adding/removing a manifest file (e.g. deleting finance.ts)
 * and re-running this script drops it from the registry with NO edit to
 * index.ts, registry.ts, or any file naming another module.
 *
 * It deliberately does NOT use import.meta.glob (which only resolves inside the
 * Vite/SvelteKit graph and throws under bare tsx/Node), so the generated barrel
 * is a plain static import list that `tsx scripts/gen-realm-export.ts` resolves
 * with no glob seam.
 *
 * Registration order is the per-manifest `order` field, NOT filename order —
 * the filenames sort content < core < ... which is not the registered sequence.
 * Files are scanned in filename order for deterministic output, then sorted by
 * `order` (ties break on filename) before emission.
 *
 * Usage:
 *   node scripts/build-module-manifest.mjs            # write index.generated.ts
 *   node scripts/build-module-manifest.mjs --stdout   # print to stdout (staleness guard)
 *
 * Exit codes:
 *   0 — barrel written / printed
 *   1 — failed to read the manifests dir, or a manifest file lacked a parseable
 *       export const <name>Manifest / order: N
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const MANIFESTS_DIR = path.resolve(__dirname, '..', 'src', 'lib', 'modules', 'manifests')
const OUT_PATH = path.join(MANIFESTS_DIR, 'index.generated.ts')

const STDOUT = process.argv.includes('--stdout')

/** Source manifest files: real *.ts modules, excluding the barrels, tests, and
 *  type declarations. */
function manifestFiles() {
  let entries
  try {
    entries = readdirSync(MANIFESTS_DIR)
  } catch (err) {
    console.error(`[module-manifest] failed to read ${MANIFESTS_DIR}: ${err.message}`)
    process.exit(1)
  }
  return entries
    .filter((f) => f.endsWith('.ts'))
    .filter((f) => !f.endsWith('.test.ts') && !f.endsWith('.d.ts'))
    .filter((f) => f !== 'index.ts' && f !== 'index.generated.ts')
    .sort()
}

/** Extract { importName, order } from a manifest file, or exit(1) if it is not a
 *  registry-shaped manifest module. */
function parseManifest(file) {
  const full = path.join(MANIFESTS_DIR, file)
  let src
  try {
    src = readFileSync(full, 'utf-8')
  } catch (err) {
    console.error(`[module-manifest] failed to read ${full}: ${err.message}`)
    process.exit(1)
  }
  const nameMatch = src.match(/export const (\w+Manifest)\s*:/)
  if (!nameMatch) {
    console.error(`[module-manifest] ${file}: no \`export const <name>Manifest: ...\` found`)
    process.exit(1)
  }
  const orderMatch = src.match(/^\s*order:\s*(\d+)\s*,/m)
  if (!orderMatch) {
    console.error(`[module-manifest] ${file}: no \`order: <number>,\` field found`)
    process.exit(1)
  }
  return { file, importName: nameMatch[1], order: Number(orderMatch[1]) }
}

function build() {
  const parsed = manifestFiles().map(parseManifest)
  // Stable sort by order, ties on filename (manifestFiles() already filename-sorted).
  parsed.sort((a, b) => a.order - b.order || a.file.localeCompare(b.file))

  const imports = parsed
    .map((p) => `import { ${p.importName} } from './${p.file.replace(/\.ts$/, '')}'`)
    .join('\n')
  const arrayItems = parsed.map((p) => `  ${p.importName},`).join('\n')

  return (
    '// @generated by scripts/build-module-manifest.mjs — DO NOT EDIT BY HAND.\n' +
    '// Re-run `node scripts/build-module-manifest.mjs` after adding/removing/renaming\n' +
    '// a manifests/*.ts file or changing its `order`. The committed copy is byte-pinned\n' +
    "// by registry.test.ts's staleness guard.\n" +
    '//\n' +
    '// SCANNED manifests/*.ts → sorted by each manifest\'s `order` field. This is the\n' +
    '// SINGLE source of the registered module set + order; no import.meta.glob (a\n' +
    '// static import list resolves under bare tsx/Node, not just the Vite graph).\n' +
    "import type { ModuleManifest } from '../types'\n" +
    imports +
    '\n\n' +
    '/** All registered module manifests, in `order` (registration) sequence. */\n' +
    'export const MODULE_MANIFESTS: ModuleManifest[] = [\n' +
    arrayItems +
    '\n]\n'
  )
}

function main() {
  const out = build()
  if (STDOUT) {
    process.stdout.write(out)
    return
  }
  writeFileSync(OUT_PATH, out, 'utf-8')
  console.info(`[module-manifest] wrote ${OUT_PATH}`)
}

main()
